// в английском месяцы и дни недели всегда с заглавной
const up = <T extends Record<string, string>>(o: T) => {
  const r: Record<string, string> = {};
  for (const [k, v] of Object.entries(o)) {
    r[k] = cap(v);
    r[cap(k)] = cap(v);
    r[k.toUpperCase()] = v.toUpperCase();
  }
  return r;
};

