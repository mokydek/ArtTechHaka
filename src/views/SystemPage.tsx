import { useDiary } from '../App';
import { MODES, PARTICLE_NAMES } from '../lib/design/system';
import type { ModeId, ParticleKind } from '../lib/types';

export default function SystemPage() {
  const { days, covers } = useDiary();
  const byMode = (m: ModeId) => days.find((d) => d.design.mode === m && covers[d.id]);
  return (
    <div>
      <div className="sec">
        <b>●</b> правила, по которым настроение становится формой
      </div>
      <h1 className="h1" style={{ maxWidth: 900 }}>
        Визуальная система: <em>один дневник, разные дни</em>
      </h1>
      <p className="muted" style={{ maxWidth: 760, fontSize: 16 }}>
        Каждая страница, вертикальный лист 4:5 (1080×1350), живой: движется в ритм песни и звучит. Постоянные элементы делают ленту дневником одного человека, переменные, делают каждый день своим. Ни одна страница не выбирается из готовых шаблонов: всё считается из текста, фото и музыки.
      </p>

      <div className="box" style={{ marginTop: 28 }}>
        <div className="sec">Проверка лентой</div>
        <div className="strip">
          {days
            .filter((d) => covers[d.id])
            .slice(0, 9)
            .map((d) => (
              <a key={d.id} href={`#/day/${d.id}`}>
                <img src={covers[d.id]} alt={d.title} title={d.title} />
              </a>
            ))}
        </div>
      </div>

      <div className="cols box">
        <div>
          <div className="sec">Постоянное, то, что делает ленту цельной</div>
          <ul className="list">
            <li>
              <b>Формат и бумага.</b> Лист 4:5 с фактурой бумаги; оттенок бумаги чуть теплее или холоднее, но всегда светлый.
            </li>
            <li>
              <b>Сетка.</b> Поля 72 px; шапка с номером страницы и датой; поле фото 936×872; блок названия; рукописная подпись; подвал.
            </li>
            <li>
              <b>Шрифты.</b> Imprint Serif, свой шрифт для названий (мягкие углы и растёкшаяся краска, на основе Lora); Caveat, рукописная подпись; Imprint Text, свой текстовый шрифт для интерфейса и служебных строк. Меняется начертание, не семейство.
            </li>
            <li>
              <b>Дорожка песни.</b> Внизу каждой страницы, волна выбранного фрагмента, окрашенная палитрой дня, и строка «исполнитель, песня · BPM · лад · приём».
            </li>
            <li>
              <b>Печать настроения.</b> Кружок с точкой: по горизонтали тепло, по вертикали энергия. Пять квадратов, палитра дня.
            </li>
            <li>
              <b>Подпись.</b> Самая «чувственная» фраза записи (запахи, звуки, свет, слова настроения), написанная от руки и появляющаяся буква за буквой.
            </li>
          </ul>
        </div>
        <div>
          <div className="sec">Переменное, то, что следует за днём</div>
          <ul className="list">
            <li>
              <b>Палитра.</b> Доминирующие цвета фото (k-means в Lab), сдвинутые к янтарю или стали по «теплу» дня; насыщенность растёт с радостью и энергией, падает в миноре.
            </li>
            <li>
              <b>Приём обработки.</b> Один из шести (ниже), выбирается по сумме признаков; в объяснении дня видно, сколько набрал каждый.
            </li>
            <li>
              <b>Ритм.</b> Кадр меняется каждые 2/4/8/16 долей песни, чем выше энергия, тем короче. Формы пульсируют в долю, свечение, от громкости.
            </li>
            <li>
              <b>Воздух.</b> Медленная минорная песня и день наедине с собой дают больше пустоты вокруг кадра.
            </li>
            <li>
              <b>Погода внутри.</b> Частицы из текста: {(['leaves', 'snow', 'rain', 'motes', 'fireflies', 'confetti', 'sparks', 'stars'] as ParticleKind[]).map((k) => PARTICLE_NAMES[k]).join(', ')}.
            </li>
            <li>
              <b>Зерно и фактура.</b> Растут с «ностальгией»: год песни, слова-воспоминания, плёночный приём.
            </li>
          </ul>
        </div>
      </div>

      <div className="box">
        <div className="sec">Шесть художественных приёмов</div>
        <div className="modes">
          {(Object.keys(MODES) as ModeId[]).map((m) => {
            const ex = byMode(m);
            const info = MODES[m];
            return (
              <div className="mode" key={m}>
                {ex && (
                  <a href={`#/day/${ex.id}`}>
                    <img src={covers[ex.id]} alt={ex.title} />
                  </a>
                )}
                <h3>{info.name}</h3>
                <div className="ref">{info.ref}</div>
                <p>
                  <b>Когда:</b> {info.when}.
                </p>
                <p>
                  <b>Как:</b> {info.technique}.
                </p>
                <p className="note">{info.why}.</p>
              </div>
            );
          })}
        </div>
      </div>

      <div className="cols box">
        <div>
          <div className="sec">Названия папок</div>
          <p>
            Всегда именная фраза из 3–7 слов, без глаголов и точки, с заглавной буквы. Система собирает её из найденного в записи по шаблонам с согласованием рода: «время + с кем + где» (<i>Вечер с девушкой у пруда</i>), «время + где + событие» (<i>Ночь в офисе перед сдачей</i>), «сезон + место + деталь» (<i>Осенний парк и какао</i>), «событие + где» (<i>Первый снег во дворе</i>), «погода + время + где» (<i>Дождливый день дома</i>). Название можно поправить перед сохранением.
          </p>
        </div>
        <div>
          <div className="sec">Голос озвучки</div>
          <p>
            Голос выбирается правилом, а не случайно: темп растёт с энергией дня (×0,8…×1,2), высота, с настроением, паузы между фразами, с «воздухом». Спокойный тёплый день читает тихий женский голос с долгими паузами; напряжённая ночь, собранный мужской. Пока звучит голос, музыка приглушается.
          </p>
          <p className="note">Настроение, художественная интерпретация, а не психологическая или медицинская оценка.</p>
        </div>
      </div>
    </div>
  );
}
